/** Categoría de un hotel según su número de estrellas. */
public enum Categoria {
    /** Una estrella. */
    ONE_STAR,

    /** Dos estrellas. */
    TWO_STARS,

    /** Tres estrellas. */
    THREE_STARS,

    /** Cuatro estrellas. */
    FOUR_STARS,

    /** Cinco estrellas. */
    FIVE_STARS
}
